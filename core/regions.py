# Нижній регістр для регістронезалежної миттєвої нормалізації (O(1))
REGION_ALIASES_LOWER = {k.lower(): v for k, v in REGION_ALIASES.items()}


def normalize_region_name(raw_name: str) -> str:
    """
    Приводить будь-яку розпізнану фразу, скорочення чи назву міста до офіційного канонічного імені області.
    Підтримує точний та регістронезалежний O(1) пошук.
    """
    if not raw_name:
        return raw_name
    name_clean = raw_name.strip()
    if name_clean in ALL_REGIONS:
        return name_clean
    if name_clean in REGION_ALIASES:
        return REGION_ALIASES[name_clean]
        
    name_lower = name_clean.lower()
    if name_lower in REGION_ALIASES_LOWER:
        return REGION_ALIASES_LOWER[name_lower]

    if name_clean in PERMANENTLY_OCCUPIED_REGIONS:
        return "АР Крим" if ("крим" in name_lower or "севастопол" in name_lower) else "Луганська область"
        
    for canonical_name, data in ALL_REGIONS.items():
        for kw in data["keywords"]:
            if kw in name_lower:
                return canonical_name
    return raw_name


def extract_region_specific_text(text: str, target_region: str) -> str:
    """
    Якщо допис у Telegram містить зведення по кількох областях (наприклад: 🛵Харківщина... 🛵Сумщина... 🛵Одещина...),
    виділяє тільки блок тексту, що стосується конкретно target_region.
    """
    if not text or not target_region:
        return text

    import re
    blocks = re.split(r'\n(?=[🛵📍▪️•▶️🔻●]|\b[А-ЯІЇЄ][а-яіїє]+щ?ина:)', text.strip())
    if len(blocks) <= 1:
        blocks = text.strip().split("\n\n")

    if len(blocks) <= 1:
        return text

    target_data = ALL_REGIONS.get(target_region)
    if not target_data:
        return text

    keywords = target_data.get("keywords", [])
    matching_blocks = []

    for block in blocks:
        block_lower = block.lower()
        if any(kw in block_lower for kw in keywords):
            matching_blocks.append(block.strip())

    if matching_blocks:
        return "\n\n".join(matching_blocks)
    
    return text
